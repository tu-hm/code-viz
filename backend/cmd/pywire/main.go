// Pywire writes the wire protocol as Python TypedDicts, so pyright can check the tracers against schema/wire.v1.schema.json.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

const usage = "usage: pywire <wire.v1.schema.json> <out.py>\n"

const header = `# Code generated by make gen from schema/wire.v1.schema.json. DO NOT EDIT.

from __future__ import annotations

from typing import Literal, NotRequired, TypeAlias, TypedDict
`

type node struct {
	Defs                 map[string]*node  `json:"$defs"`
	Ref                  string            `json:"$ref"`
	Type                 types             `json:"type"`
	Enum                 []json.RawMessage `json:"enum"`
	Const                json.RawMessage   `json:"const"`
	Properties           map[string]*node  `json:"properties"`
	Required             []string          `json:"required"`
	AdditionalProperties *node             `json:"additionalProperties"`
	Items                *node             `json:"items"`
	AllOf                []*node           `json:"allOf"`
	AnyOf                []*node           `json:"anyOf"`
	If                   *node             `json:"if"`
	Then                 *node             `json:"then"`
}

// any other keyword is refused: a new schema feature must not silently become a looser type
var keywords = map[string]bool{
	"$defs": true, "$ref": true, "type": true, "enum": true, "const": true, "properties": true, "required": true,
	"additionalProperties": true, "items": true, "allOf": true, "anyOf": true, "if": true, "then": true,
	"$schema": true, "$id": true, "title": true, "description": true, "minimum": true, "maximum": true,
	"minLength": true, "minItems": true, "maxItems": true, "pattern": true, "propertyNames": true,
}

func (n *node) UnmarshalJSON(b []byte) error {
	var raw map[string]json.RawMessage
	if err := json.Unmarshal(b, &raw); err != nil {
		return err
	}
	for k := range raw {
		if !keywords[k] {
			return fmt.Errorf("unsupported keyword %q", k)
		}
	}
	type plain node
	return json.Unmarshal(b, (*plain)(n))
}

type types []string

func (t *types) UnmarshalJSON(b []byte) error {
	if bytes.HasPrefix(b, []byte(`"`)) {
		var s string
		if err := json.Unmarshal(b, &s); err != nil {
			return err
		}
		*t = types{s}
		return nil
	}
	return json.Unmarshal(b, (*[]string)(t))
}

type gen struct {
	dir     string
	files   map[string]*node
	classes map[string]string
	aliases map[string]string
	sources map[string]string
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprint(os.Stderr, usage)
		os.Exit(2)
	}
	src, err := generate(os.Args[1])
	if err == nil {
		err = os.WriteFile(os.Args[2], src, 0o644) //nolint:gosec // generated source, as readable as the rest of the repo
	}
	if err != nil {
		fmt.Fprintf(os.Stderr, "pywire: %v\n", err)
		os.Exit(1)
	}
}

func generate(path string) ([]byte, error) {
	g := &gen{dir: filepath.Dir(path), files: map[string]*node{}, classes: map[string]string{},
		aliases: map[string]string{}, sources: map[string]string{}}
	file := filepath.Base(path)
	root, err := g.load(file)
	if err != nil {
		return nil, err
	}

	var messages []string
	for _, branch := range root.AllOf {
		if branch.If == nil || branch.If.Properties["type"] == nil || branch.Then == nil || branch.Then.Ref == "" {
			return nil, fmt.Errorf("%s: each allOf entry must map a type const to a $ref", file)
		}
		name, err := g.def(file, branch.Then.Ref, branch.If.Properties["type"].Const)
		if err != nil {
			return nil, err
		}
		messages = append(messages, name)
	}
	if len(messages) == 0 {
		return nil, fmt.Errorf("%s: no message types", file)
	}
	slices.Sort(messages)
	g.aliases["Message"] = strings.Join(messages, " | ")

	var out strings.Builder
	out.WriteString(header)
	for _, name := range slices.Sorted(maps.Keys(g.classes)) {
		fmt.Fprintf(&out, "\n\nclass %s(TypedDict):\n%s", name, g.classes[name])
	}
	out.WriteString("\n\n")
	for _, name := range slices.Sorted(maps.Keys(g.aliases)) {
		fmt.Fprintf(&out, "%s: TypeAlias = %s\n", name, g.aliases[name])
	}
	return []byte(out.String()), nil
}

func (g *gen) load(file string) (*node, error) {
	if n, ok := g.files[file]; ok {
		return n, nil
	}
	b, err := os.ReadFile(filepath.Join(g.dir, file)) //nolint:gosec // a schema file next to the one make gen names
	if err != nil {
		return nil, err
	}
	var n node
	if err := json.Unmarshal(b, &n); err != nil {
		return nil, fmt.Errorf("%s: %w", file, err)
	}
	g.files[file] = &n
	return &n, nil
}

func (g *gen) def(file, ref string, tag json.RawMessage) (string, error) {
	path, name, def, err := g.resolve(file, ref)
	if err != nil {
		return "", err
	}
	py := pascal(name)
	if def.Properties != nil {
		return g.class(path, py, path+"#"+name, def, tag)
	}
	if err := g.claim(py, path+"#"+name); err != nil {
		return "", err
	}
	if _, done := g.aliases[py]; done {
		return py, nil
	}
	expr, err := g.expr(path, py, def)
	if err != nil {
		return "", fmt.Errorf("%s#%s: %w", path, name, err)
	}
	g.aliases[py] = expr
	return py, nil
}

func (g *gen) resolve(file, ref string) (string, string, *node, error) {
	path, frag, _ := strings.Cut(ref, "#")
	if path == "" {
		path = file
	}
	name, ok := strings.CutPrefix(frag, "/$defs/")
	if !ok {
		return "", "", nil, fmt.Errorf("%s: unsupported $ref %q", file, ref)
	}
	root, err := g.load(path)
	if err != nil {
		return "", "", nil, err
	}
	def := root.Defs[name]
	if def == nil {
		return "", "", nil, fmt.Errorf("%s: $ref %q not found", file, ref)
	}
	return path, name, def, nil
}

func (g *gen) claim(py, source string) error {
	if prev, ok := g.sources[py]; ok && prev != source {
		return fmt.Errorf("%s and %s both become %s", prev, source, py)
	}
	g.sources[py] = source
	return nil
}

func (g *gen) class(file, py, source string, n *node, tag json.RawMessage) (string, error) {
	if err := g.claim(py, source); err != nil {
		return "", err
	}
	if _, done := g.classes[py]; done {
		return py, nil
	}

	props := map[string]*node{}
	required := map[string]bool{}
	if err := g.merge(file, n, props, required); err != nil {
		return "", err
	}
	fields := map[string]string{}
	if tag != nil {
		lit, err := literal(tag)
		if err != nil {
			return "", fmt.Errorf("%s: %w", source, err)
		}
		fields["type"] = lit
	}
	for name, p := range props {
		expr, err := g.expr(file, py+pascal(name), p)
		if err != nil {
			return "", fmt.Errorf("%s.%s: %w", source, name, err)
		}
		if !required[name] {
			expr = "NotRequired[" + expr + "]"
		}
		fields[name] = expr
	}

	var body strings.Builder
	for _, name := range slices.Sorted(maps.Keys(fields)) {
		fmt.Fprintf(&body, "    %s: %s\n", name, fields[name])
	}
	g.classes[py] = body.String()
	return py, nil
}

func (g *gen) merge(file string, n *node, props map[string]*node, required map[string]bool) error {
	maps.Copy(props, n.Properties)
	for _, name := range n.Required {
		required[name] = true
	}
	for _, sub := range n.AllOf {
		// if/then only makes more fields required for one kind; the class keeps them NotRequired
		if sub.If != nil {
			continue
		}
		if sub.Ref == "" {
			return fmt.Errorf("%s: allOf entry is neither $ref nor if/then", file)
		}
		path, _, def, err := g.resolve(file, sub.Ref)
		if err != nil {
			return err
		}
		if err := g.merge(path, def, props, required); err != nil {
			return err
		}
	}
	return nil
}

func (g *gen) expr(file, py string, n *node) (string, error) {
	switch {
	case n.Ref != "":
		return g.def(file, n.Ref, nil)
	case n.AnyOf != nil:
		var parts []string
		for _, sub := range n.AnyOf {
			expr, err := g.expr(file, py, sub)
			if err != nil {
				return "", err
			}
			parts = append(parts, expr)
		}
		return strings.Join(parts, " | "), nil
	case n.Enum != nil:
		return literal(n.Enum...)
	case n.Const != nil:
		return literal(n.Const)
	case n.Type == nil:
		return "", errors.New("no type, $ref, anyOf, enum or const")
	}

	var parts []string
	for _, t := range n.Type {
		switch t {
		case "string":
			parts = append(parts, "str")
		case "integer":
			parts = append(parts, "int")
		case "number":
			parts = append(parts, "float")
		case "boolean":
			parts = append(parts, "bool")
		case "null":
			parts = append(parts, "None")
		case "array":
			if n.Items == nil {
				return "", errors.New("array without items")
			}
			item, err := g.expr(file, py, n.Items)
			if err != nil {
				return "", err
			}
			parts = append(parts, "list["+item+"]")
		case "object":
			expr, err := g.object(file, py, n)
			if err != nil {
				return "", err
			}
			parts = append(parts, expr)
		default:
			return "", fmt.Errorf("unsupported type %q", t)
		}
	}
	return strings.Join(parts, " | "), nil
}

func (g *gen) object(file, py string, n *node) (string, error) {
	if n.Properties != nil {
		return g.class(file, py, file+"#"+py, n, nil)
	}
	if n.AdditionalProperties == nil {
		return "dict[str, object]", nil
	}
	value, err := g.expr(file, py, n.AdditionalProperties)
	if err != nil {
		return "", err
	}
	return "dict[str, " + value + "]", nil
}

func literal(values ...json.RawMessage) (string, error) {
	var parts []string
	for _, v := range values {
		var s string
		var i int64
		switch {
		case json.Unmarshal(v, &s) == nil:
			parts = append(parts, strconv.Quote(s))
		case json.Unmarshal(v, &i) == nil:
			parts = append(parts, strconv.FormatInt(i, 10))
		default:
			return "", fmt.Errorf("unsupported literal %s", v)
		}
	}
	return "Literal[" + strings.Join(parts, ", ") + "]", nil
}

func pascal(name string) string {
	return strings.ToUpper(name[:1]) + name[1:]
}
