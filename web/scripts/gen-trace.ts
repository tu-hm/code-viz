import { readFile, writeFile } from 'node:fs/promises'
import { compile, type JSONSchema } from 'json-schema-to-typescript'

type Schema = JSONSchema & {
  $defs: Record<string, { properties: Record<string, { enum: string[]; tsType?: string }> }>
}

const input = '../backend/schema/trace.v1.schema.json'
const output = 'packages/player/src/gen/trace.ts'

const schema = JSON.parse(await readFile(input, 'utf8')) as Schema

// open unions: a newer minor version may send a t or kind this build does not know (§9.7)
for (const [def, prop] of Object.entries({ value: 't', heapObject: 'kind' })) {
  const p = schema.$defs[def]?.properties[prop]
  if (!p) throw new Error(`${input}: no $defs.${def}.properties.${prop}`)
  p.tsType = [...p.enum.map((e) => JSON.stringify(e)), '(string & {})'].join(' | ')
}

const ts = await compile(schema, 'Trace', {
  additionalProperties: false,
  unreachableDefinitions: true,
  bannerComment: `// Code generated by pnpm gen from backend/schema/trace.v1.schema.json. DO NOT EDIT.`,
})
await writeFile(output, ts)
